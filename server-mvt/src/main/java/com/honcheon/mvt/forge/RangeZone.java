package com.honcheon.mvt.forge;

/**
 * 산세 구역 — 영역 11구역(hwasan_domain_design.md)의 방사 투영.
 *
 * <p>큰 골격(정상·본산·후산·입구·외곽)의 경계는 H-6 확정 깊이(140/30/150)와
 * {@code footprint_radius_min} 124 (H-7)에서 방사 유도된다 — {@link RangeField#zoneAt} 가
 * 그 실물이다. <b>다만 곁구역 넷(매화림·계곡·절벽·연무 계곡)의 안쪽 가름은 방사 띠(각 35)가
 * 아니라 등산로가 꿴다</b> (Q9 확정 — 회차 A-2). {@code zoneAt} 이 중간 고리를 등산로 폴리라인
 * 위 호장 비율로 재단하므로 이 경계는 노선을 따라 굽이친다 (재단 방식 terrain_forge_v5.md §2.3).
 *
 * <p>본산권 안의 세분(본산 하단/중단/상단 · 장로 구역)은 여기 없다 — 그것은 단 사슬
 * 배치기(기계 ⑥)의 소유다 (브리프 §1.3 표). 후산은 방위(주봉 북면)로 갈린다.
 */
public enum RangeZone {
    /** 구역 11 — 정상 (성역 · 건축 최소화: 수행대·전망대) */
    SUMMIT,
    /** 구역 10 — 후산 (주봉 북면 · 비밀 지역) */
    HUSAN,
    /** 구역 8~9 — 본산권 남면 (단 사슬·장로 구역 — 세분은 배치기 ⑥) */
    HONSAN,
    /** 구역 7 — 연무 계곡 (야외 수련장) */
    DRILL_VALLEY,
    /** 구역 6 — 절벽 (난이도 높은 이동 구간) */
    CLIFF,
    /** 구역 5 — 계곡 (폭포·개울 — 수계 ②의 자리) */
    VALLEY,
    /** 구역 4 — 매화림 (분위기 연출) */
    PLUM_GROVE,
    /** 구역 2(+3 시점) — 화산 입구 (패방·상업 거리·외문) */
    ENTRANCE,
    /** 구역 1 — 외곽 평원 (화산촌·농경지) */
    OUTER_PLAIN,
    /** 경제권 밖 — 회랑·야생의 몫 (노선 조성기 — 이 기계의 소유 밖) */
    OUTSIDE
}
