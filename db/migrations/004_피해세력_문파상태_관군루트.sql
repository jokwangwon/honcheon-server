-- 004 — 연합의 브레이크 (피해 세력 · 문파 상태) + 관군 루트
--
-- 배경 ① — **연합이 너무 쉽게 뭉쳤다.**
--   003 이 깐 명분층은 음(−) 보정만 배선돼 있었다:
--     · 사안에 **피해 세력 필드가 없어서** 피해_당사자(-8)·동맹_피해(-6)·원한_세력_참여(+5)가 전부 죽었다
--       → '누가 당했는가'를 모르니 당사자도 동맹도 원수도 계산에 들어오지 못했다
--     · 문파 상태 축이 없어서 자파_내부_사정(+0~+6)을 읽을 수가 없었다
--       → '제 코가 석 자인' 문파도 언제나 남의 싸움에 낄 수 있었다
--   결과: 명분 10 짜리 사건 하나에 20개 세력 중 17개가 붙었다 (설계는 명분 27 에 8~12 를 예상).
--   그런 세계에서는 **관이 아무것도 못 한다** — 관무불가침이 관의 항복 문서가 된다.
--
-- 배경 ② — **관에 드는 길이 없었다.**
--   faction_entry_routes 8루트에 관이 빠져 있었다 (정파·세가·사파4·마교·혈교).
--   관군 루트는 계급을 시트 태그로 든다 — 새 표를 만들지 않는다 (계급은 사람의 것이지 세계의 것이 아니다).
--
-- 설계 원칙 (003 그대로):
--   · 연합에는 표가 없다 — **상태가 아니라 함수다** (Politics.form). 저장할 것이 없으니 어긋날 것도 없다.
--   · 감쇠는 배치 잡이 아니라 **읽는 순간** 정산한다. 같은 세계일이면 같은 세계.

-- ── ① 사안에 '누가 당했는가'를 적는다 ────────────────────────────────────
-- target 은 '누가 했는가'다. victims 는 '누가 당했는가'다.
-- 이 한 칸이 없어서 연합 계산의 절반이 죽어 있었다.
ALTER TABLE myeongbun ADD COLUMN victims_json TEXT NOT NULL DEFAULT '[]';

-- ── ② 문파 상태 (자파 내부 사정) ─────────────────────────────────────────
-- 0~6. 남의 싸움에 낼 여력이 얼마나 없는가.
-- 기준선은 config (faction_politics roster.<세력>.internal_burden) 에 있고,
-- 이 표는 **사건이 얹은 것**만 든다 (장문 교체기 +3 · 내분 +2 · 사상자 +2 · 재정 궁핍 +1).
--   ★ '다른 전쟁 중(+4)' 은 저장하지 않는다 — 오늘의 연합에서 읽으면 되는 값이다 (파생 상태 금지).
-- 규칙: sect_life.yml sect_state.internal_burden
CREATE TABLE IF NOT EXISTS sect_state (
    faction      TEXT PRIMARY KEY,
    burden       INTEGER NOT NULL DEFAULT 0,   -- 사건이 얹은 부담 (기준선은 config)
    sources_json TEXT NOT NULL DEFAULT '[]',   -- 무엇 때문인가 (장문_교체기 · 내분_알력 …)
    updated_day  INTEGER NOT NULL
);

